//! Installed-app inventory: `apt-mark showmanual` + `flatpak list`.
//! The Apps screen merges this real list with the saved selection, and the
//! flash wizard writes the ticked apps as the stick's install list
//! (consumed by setup/install-packages.sh on first boot).

use std::process::Command;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum AppSource {
    Apt,
    Flatpak,
}

#[derive(Clone, Debug)]
pub struct InventoryEntry {
    /// apt package name or flatpak application ID.
    pub id: String,
    pub source: AppSource,
}

/// Manually installed apt packages on this PC.
pub fn apt_manual() -> Vec<String> {
    let Ok(out) = Command::new("apt-mark").arg("showmanual").output() else {
        return Vec::new();
    };
    if !out.status.success() {
        return Vec::new();
    }
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .filter(|name| !looks_like_library(name))
        .map(str::to_string)
        .collect()
}

/// Shared-library packages are dependencies, not apps a user picks.
/// A plain "starts with lib" filter also hides libreoffice-*, librecad
/// and friends, so only drop names that look like versioned shared
/// libs (libfoo2, libqt6core6t64, libbar-3) unless the package is a
/// known app with a lib* name.
fn looks_like_library(name: &str) -> bool {
    /// lib-prefixed packages that are real applications.
    const KNOWN_LIB_APPS: &[&str] = &[
        "libreoffice",
        "librecad",
        "librewolf",
        "librepcb",
        "libresprite",
    ];
    let Some(rest) = name.strip_prefix("lib") else {
        return false;
    };
    if rest.is_empty() {
        return true;
    }
    if KNOWN_LIB_APPS
        .iter()
        .any(|app| name == *app || name.starts_with(&format!("{app}-")))
    {
        return false;
    }
    // Versioned soname packages (libpng16, libssl3t64, libqt6core6t64,
    // libfoo-2) carry digits; the app names above do not.
    rest.starts_with('-') || rest.chars().any(|c| c.is_ascii_digit())
}

#[cfg(test)]
mod lib_filter_tests {
    use super::looks_like_library;

    #[test]
    fn drops_shared_libs_keeps_apps() {
        for lib in ["libssl3", "libqt6core6t64", "libpng16-16t64", "libglib2.0-0t64"] {
            assert!(looks_like_library(lib), "{lib} should be filtered");
        }
        for app in [
            "libreoffice",
            "libreoffice-core",
            "libreoffice-writer",
            "librecad",
            "htop",
            "firefox",
            "git",
        ] {
            assert!(!looks_like_library(app), "{app} must stay visible");
        }
    }
}

/// Installed flatpak application IDs.
pub fn flatpak_apps() -> Vec<String> {
    let Ok(out) = Command::new("flatpak")
        .args(["list", "--app", "--columns=application"])
        .output()
    else {
        return Vec::new();
    };
    if !out.status.success() {
        return Vec::new();
    }
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .map(str::to_string)
        .collect()
}

/// Full inventory: apt section first, then flatpaks, both sorted.
pub fn inventory() -> Vec<InventoryEntry> {
    let mut entries: Vec<InventoryEntry> = apt_manual()
        .into_iter()
        .map(|id| InventoryEntry {
            id,
            source: AppSource::Apt,
        })
        .collect();
    entries.extend(flatpak_apps().into_iter().map(|id| InventoryEntry {
        id,
        source: AppSource::Flatpak,
    }));
    entries.sort_by(|a, b| {
        a.source
            .cmp_key()
            .cmp(&b.source.cmp_key())
            .then_with(|| a.id.to_lowercase().cmp(&b.id.to_lowercase()))
    });
    entries
}

impl AppSource {
    fn cmp_key(self) -> u8 {
        match self {
            AppSource::Apt => 0,
            AppSource::Flatpak => 1,
        }
    }
}

/// Render the install list the stick consumes on first boot:
/// apt package names under [apt], flatpak IDs under [flatpak].
pub fn render_install_list(selected: &[InventoryEntry]) -> String {
    let mut out = String::from("# generated by kubuntu-usb-sync\n[apt]\n");
    for entry in selected.iter().filter(|e| e.source == AppSource::Apt) {
        out.push_str(&entry.id);
        out.push('\n');
    }
    out.push_str("[flatpak]\n");
    for entry in selected.iter().filter(|e| e.source == AppSource::Flatpak) {
        out.push_str(&entry.id);
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn install_list_splits_sections() {
        let selected = vec![
            InventoryEntry { id: "htop".into(), source: AppSource::Apt },
            InventoryEntry { id: "org.videolan.VLC".into(), source: AppSource::Flatpak },
        ];
        let list = render_install_list(&selected);
        assert!(list.contains("[apt]\nhtop\n"));
        assert!(list.contains("[flatpak]\norg.videolan.VLC\n"));
    }
}
