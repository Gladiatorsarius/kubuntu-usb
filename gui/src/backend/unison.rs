//! Unison profile generation and sync runs.
//!
//! Conflict policy mirrors sync/school-home.prf from the repo: two-way
//! profiles never pick a winner (`auto = true`, `batch = true`, no
//! `prefer`), so a file changed on both sides is reported and left alone.
//! One-way folders (PC wins / Stick wins) are generated with `force` on
//! the winning root.

use crate::config::{FolderConfig, SyncMode};
use std::io::{BufRead, BufReader};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::mpsc::Sender;

/// Ignore rules shared by all generated profiles (from the repo's .prf files).
const IGNORE_RULES: &[&str] = &[
    "Name .unison",
    "Name .unison.*",
    "Name *.unison.tmp",
    "Name SingletonCookie",
    "Name SingletonLock",
    "Name SingletonSocket",
    "Name .parentlock",
    "Name parent.lock",
    "Name .~lock.*#",
    "Path .cache",
    "Path .local/share/Trash",
];

/// Render a Unison profile for one sync folder.
///
/// `pc_home` / `stick_home` are the home directories on each side; the
/// folder path is taken relative to them (a leading "~/" is stripped).
pub fn profile_for(folder: &FolderConfig, pc_home: &str, stick_home: &str) -> String {
    let rel = folder.path.trim_start_matches("~/");
    let pc_root = format!("{pc_home}/{rel}");
    let stick_root = format!("{stick_home}/{rel}");

    let mut profile = format!(
        "# generated by kubuntu-usb-sync\nroot = {pc_root}\nroot = {stick_root}\n\
         auto = true\nbatch = true\ntimes = true\nbackup = Name *\nbackuplocation = central\n"
    );
    for rule in IGNORE_RULES {
        profile.push_str(&format!("ignore = {rule}\n"));
    }
    match folder.mode {
        SyncMode::BothWays => {}
        SyncMode::PcWins => profile.push_str(&format!("force = {pc_root}\n")),
        SyncMode::StickWins => profile.push_str(&format!("force = {stick_root}\n")),
    }
    profile
}

/// Write all folder profiles into `dir` (one .prf per folder, name-sanitized).
pub fn write_profiles(
    folders: &[FolderConfig],
    pc_home: &str,
    stick_home: &str,
    dir: &Path,
) -> std::io::Result<Vec<PathBuf>> {
    std::fs::create_dir_all(dir)?;
    let mut written = Vec::new();
    for (index, folder) in folders.iter().enumerate() {
        let name: String = folder
            .path
            .trim_start_matches("~/")
            .chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
            .collect();
        let path = dir.join(format!("{index:02}-{name}.prf"));
        std::fs::write(&path, profile_for(folder, pc_home, stick_home))?;
        written.push(path);
    }
    Ok(written)
}

/// Events streamed back from a running sync.
#[derive(Clone, Debug)]
pub enum SyncEvent {
    /// A status/action line from unison (e.g. "BGN Copying notes.txt ...").
    Line(String),
    /// Unison reported a conflict for this path (left unresolved).
    Conflict(String),
    /// One profile finished; index into the folder list.
    FolderDone(usize),
    /// Whole run finished; true when no conflicts were found.
    Finished(bool),
}

/// Run unison for every folder profile, streaming events to `tx`.
/// Blocking - call from a worker thread.
pub fn run_sync(
    profiles: Vec<PathBuf>,
    backup_dir: &Path,
    tx: Sender<SyncEvent>,
) -> std::io::Result<()> {
    let mut clean = true;
    for (index, profile) in profiles.iter().enumerate() {
        let mut child = Command::new("unison")
            .arg(profile)
            .arg("-backupdir")
            .arg(backup_dir)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()?;

        if let Some(stdout) = child.stdout.take() {
            for line in BufReader::new(stdout).lines() {
                let Ok(line) = line else { break };
                if line.contains("CONFLICT") {
                    clean = false;
                    let path = line
                        .rsplit("CONFLICT")
                        .next()
                        .unwrap_or("")
                        .trim()
                        .to_string();
                    let _ = tx.send(SyncEvent::Conflict(path));
                }
                let _ = tx.send(SyncEvent::Line(line));
            }
        }
        let status = child.wait()?;
        if !status.success() {
            clean = false;
        }
        let _ = tx.send(SyncEvent::FolderDone(index));
    }
    let _ = tx.send(SyncEvent::Finished(clean));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{FolderConfig, SyncMode};

    fn folder(mode: SyncMode) -> FolderConfig {
        FolderConfig {
            path: "~/School".into(),
            description: String::new(),
            mode,
        }
    }

    #[test]
    fn both_ways_has_no_force() {
        let profile = profile_for(&folder(SyncMode::BothWays), "/home/gladi", "/media/usb/home");
        assert!(profile.contains("root = /home/gladi/School"));
        assert!(profile.contains("root = /media/usb/home/School"));
        assert!(!profile.contains("force ="));
        assert!(profile.contains("batch = true"));
    }

    #[test]
    fn pc_wins_forces_pc_root() {
        let profile = profile_for(&folder(SyncMode::PcWins), "/home/gladi", "/media/usb/home");
        assert!(profile.contains("force = /home/gladi/School"));
    }

    #[test]
    fn stick_wins_forces_stick_root() {
        let profile = profile_for(&folder(SyncMode::StickWins), "/home/gladi", "/media/usb/home");
        assert!(profile.contains("force = /media/usb/home/School"));
    }
}
